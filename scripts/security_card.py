#!/usr/bin/env python3
"""Print the README security card from the live server, so its numbers are measured, not typed.

Token footprint = characters of everything an app loads at startup (instructions, tool
definitions, prompt list) divided by 4, the usual rule of thumb for English and JSON.
Usage: python scripts/security_card.py   (paste the output into the README, or use --check in CI)
"""

from __future__ import annotations

import asyncio
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from lathe.config import Config  # noqa: E402
from lathe.modules import all_modules  # noqa: E402
from lathe.server import build_server  # noqa: E402

HOSTS = ("None. Lathe makes no network connections, and ffmpeg and ffprobe are restricted to local files "
         "(-protocol_whitelist file,pipe). --transport http listens on 127.0.0.1 only when you start it that way.")
FILES = ("Reads and writes files only inside the working folder (LATHE_WORKING_DIR). Reads its optional config file "
         "(~/.config/lathe/config.toml). Writes one local approval log (~/.local/state/lathe/approvals.jsonl).")
SECRETS = "No keys, accounts or passwords. Nothing to store, and nothing that leaves the machine."


def card() -> str:
    # Startup cost is what a fresh install loads (default modules). The tool lists cover every module.
    default = build_server(Config(env={}, file_data={}))
    srv = build_server(Config(env={"LATHE_BATCH_ENABLED": "true", "LATHE_PRIVACY_ENABLED": "true"}, file_data={}))
    tools = asyncio.run(srv.list_tools())
    prompts = asyncio.run(srv.list_prompts())
    d_tools = asyncio.run(default.list_tools())
    d_prompts = asyncio.run(default.list_prompts())
    startup = (default.instructions or "") + json.dumps([t.model_dump(exclude_none=True, mode="json") for t in d_tools]) \
        + json.dumps([p.model_dump(exclude_none=True, mode="json") for p in d_prompts])
    read_only = [t.name for t in tools if t.annotations and t.annotations.readOnlyHint]
    # Gated = the run asks the person first (ToolSpec.gated). Other writers write new files without asking.
    gated = sorted(spec.name for m in all_modules() for spec in m.tools if spec.gated)
    writes = sorted(t.name for t in tools if not (t.annotations and t.annotations.readOnlyHint) and t.name not in gated)
    return "\n".join([
        "<!-- security-card:start (generated by scripts/security_card.py) -->",
        "| Security card | |",
        "|---|---|",
        f"| Network | {HOSTS} |",
        f"| Files | {FILES} |",
        f"| Secrets | {SECRETS} |",
        f"| Read-only tools | {len(read_only)}: {', '.join(f'`{n}`' for n in read_only)} |",
        f"| Asks you first | {', '.join(f'`{n}`' for n in gated)}: the person approves each run in the MCP client, or pre-approves the module in settings (`LATHE_<MODULE>_PREAPPROVED`). The AI cannot approve for you. |",
        f"| Writes without asking | {', '.join(f'`{n}`' for n in writes)}: write a new file in the working folder and never replace an existing one unless the call passes `overwrite=true`. |",
        f"| Startup cost | about {round(len(startup) / 4, -2):,.0f} tokens for a default install ({len(d_tools)} tools, {len(d_prompts)} skill prompts) |",
        "| Changes | Tool descriptions are locked by hash (`tool-manifest.lock.json`); CI fails if they change silently. |",
        "<!-- security-card:end -->",
    ])


def main() -> int:
    text = card()
    if "--check" in sys.argv:
        readme = (ROOT / "README.md").read_text()
        m = re.search(r"<!-- security-card:start.*?<!-- security-card:end -->", readme, re.S)
        ok = bool(m) and m.group(0) == text
        print("security card is current" if ok else "README security card is stale: run scripts/security_card.py")
        return 0 if ok else 1
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
